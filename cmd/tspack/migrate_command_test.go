func TestMigrateMissingPackageJSONDiagnostic(t *testing.T) {
	root := t.TempDir()
	cfg, diags := parseMigrateArgs([]string{"migrate", "--root", root})
	if len(diags) != 0 {
		t.Fatalf("unexpected parse diagnostics: %#v", diags)
	}
	_, diagnostic := buildMigrationDraft(cfg)
	if diagnostic == nil {
		t.Fatalf("expected missing package.json diagnostic")
	}
	if diagnostic.Code != "TSPACK_MIGRATE_PACKAGE_JSON_MISSING" {
		t.Fatalf("unexpected diagnostic code: %s", diagnostic.Code)
	}
	if !strings.Contains(strings.Join(diagnostic.Details, "\n"), filepath.Join(root, "package.json")) {
		t.Fatalf("diagnostic details should include package.json path: %#v", diagnostic.Details)
	}
}

