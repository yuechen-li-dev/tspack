func TestMigrateReportStableAcrossRepeatedRuns(t *testing.T) {
	root := t.TempDir()
	writePackageJSON(t, root, `{"name":"stable","version":"1.0.0","devDependencies":{"z":"1","a":"1"},"scripts":{"test":"echo test","build":"echo build"}}`)
	cfg, _ := parseMigrateArgs([]string{"migrate", "--root", root})
	first, diagnostic := buildMigrationDraft(cfg)
	if diagnostic != nil {
		t.Fatalf("unexpected diagnostic: %#v", diagnostic)
	}
	second, diagnostic := buildMigrationDraft(cfg)
	if diagnostic != nil {
		t.Fatalf("unexpected diagnostic: %#v", diagnostic)
	}
	if first.Manifest != second.Manifest {
		t.Fatalf("manifest is not stable")
	}
	if first.Report != second.Report {
		t.Fatalf("report is not stable")
	}
}

func writePackageJSON(t *testing.T, root string, content string) {
	t.Helper()
	if err := os.WriteFile(filepath.Join(root, "package.json"), []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func assertFileMissing(t *testing.T, path string) {
	t.Helper()
	if _, err := os.Stat(path); err == nil {
		t.Fatalf("expected file to be missing: %s", path)
	} else if !os.IsNotExist(err) {
		t.Fatalf("unexpected stat error for %s: %v", path, err)
	}
}

func assertFileContains(t *testing.T, path string, want string) {
	t.Helper()
	content, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(content), want) {
		t.Fatalf("%s missing %q:\n%s", path, want, string(content))
	}
}

func repoRootForMigrateTest(t *testing.T) string {
	t.Helper()
	wd, err := os.Getwd()
	if err != nil {
		t.Fatal(err)
	}
	return filepath.Clean(filepath.Join(wd, "..", ".."))
}
