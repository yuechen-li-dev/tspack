func projectionContribution(values []projection, layout *sourceLayout) ast.Expr {
	objects := map[string][]projection{}
	order := []string{}
	for _, value := range values {
		if _, ok := objects[value.Object]; !ok {
			order = append(order, value.Object)
		}
		objects[value.Object] = append(objects[value.Object], value)
	}
	objectEntries := make([]ast.Expr, 0, len(order))
	for _, object := range order {
		fields := make([]ast.Expr, 0, len(objects[object]))
		for _, value := range objects[object] {
			fields = append(fields, &ast.KeyValueExpr{Key: stringLiteral(value.Key, layout), Value: stringLiteral(value.Value, layout)})
		}
		objectEntries = append(objectEntries, &ast.KeyValueExpr{Key: stringLiteral(object, layout), Value: &ast.CompositeLit{Type: &ast.MapType{Key: layout.ident("string"), Value: layout.ident("string")}, Lbrace: layout.take(), Elts: fields}})
	}
	objectsLiteral := &ast.CompositeLit{Type: &ast.MapType{Key: layout.ident("string"), Value: &ast.MapType{Key: layout.ident("string"), Value: layout.ident("string")}}, Lbrace: layout.take(), Elts: objectEntries}
	return composite("ProjectionContributions", []ast.Expr{keyed("Objects", objectsLiteral, layout)}, layout)
}

func fieldDecl(name, typeName string) *ast.Field {
	return &ast.Field{Names: []*ast.Ident{ast.NewIdent(name)}, Type: parseType(typeName)}
}
func parseType(name string) ast.Expr {
	if len(name) > 2 && name[:2] == "[]" {
		return &ast.ArrayType{Elt: ast.NewIdent(name[2:])}
	}
	return ast.NewIdent(name)
}
func sliceType(name string, layout *sourceLayout) *ast.ArrayType {
	return &ast.ArrayType{Lbrack: layout.take(), Elt: layout.ident(name)}
}
func composite(typeName string, fields []ast.Expr, layout *sourceLayout) *ast.CompositeLit {
	for range fields {
		layout.nextLine()
	}
	return &ast.CompositeLit{Type: layout.ident(typeName), Lbrace: layout.take(), Elts: fields}
}
func pointerComposite(typeName string, fields []ast.Expr, layout *sourceLayout) *ast.UnaryExpr {
	return &ast.UnaryExpr{OpPos: layout.take(), Op: token.AND, X: composite(typeName, fields, layout)}
}
func keyed(name string, value ast.Expr, layout *sourceLayout) *ast.KeyValueExpr {
	return &ast.KeyValueExpr{Key: layout.ident(name), Colon: layout.take(), Value: value}
}
func stringLiteral(value string, layout *sourceLayout) *ast.BasicLit {
	return &ast.BasicLit{ValuePos: layout.take(), Kind: token.STRING, Value: fmt.Sprintf("%q", value)}
}
func boolLiteral(value bool, layout *sourceLayout) *ast.Ident {
	if value {
		return layout.ident("true")
	}
	return layout.ident("false")
}

type sourceLayout struct{ next token.Pos }

func newLayout() (*token.FileSet, *sourceLayout) {
	fset := token.NewFileSet()
	file := fset.AddFile("tspack-octgen.generated.go", -1, 500000)
	content := make([]byte, 500000)
	for index := 9; index < len(content); index += 10 {
		content[index] = '\n'
	}
	file.SetLinesForContent(content)
	return fset, &sourceLayout{next: token.Pos(file.Base())}
}
func (layout *sourceLayout) take() token.Pos { position := layout.next; layout.next++; return position }
func (layout *sourceLayout) ident(name string) *ast.Ident {
	return &ast.Ident{Name: name, NamePos: layout.take()}
}
func (layout *sourceLayout) nextLine() {
	offset := int(layout.next - 1)
	layout.next = token.Pos(((offset/10)+1)*10 + 1)
}
func modelError(provenance, format string, arguments ...any) error {
	return fmt.Errorf("TSPack OctGen model %s: %s", provenance, fmt.Sprintf(format, arguments...))
}
func fatal(format string, arguments ...any) {
	fmt.Fprintf(os.Stderr, "generate-concepts: "+format+"\n", arguments...)
	os.Exit(1)
}
