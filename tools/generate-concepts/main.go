func renderRegistry(value model) ([]byte, error) {
	fset, layout := newLayout()
	decl := &ast.FuncDecl{Name: layout.ident("builtinFragments"), Type: &ast.FuncType{Results: &ast.FieldList{List: []*ast.Field{{Type: sliceType("Fragment", layout)}}}}, Body: &ast.BlockStmt{List: []ast.Stmt{&ast.ReturnStmt{Results: []ast.Expr{fragmentSlice(value.Concepts, layout)}}}}}
	return formatFile(fset, value.Package, []ast.Decl{decl})
}

func renderExpectations(value model) ([]byte, error) {
	fset, layout := newLayout()
	typeDecl := &ast.GenDecl{
		Tok: token.TYPE,
		Specs: []ast.Spec{&ast.TypeSpec{
			Name: ast.NewIdent("generatedCompositionCase"),
			Type: &ast.StructType{Fields: &ast.FieldList{List: []*ast.Field{
				fieldDecl("Name", "string"),
				fieldDecl("Kind", "string"),
				fieldDecl("Concepts", "[]string"),
				fieldDecl("Dependencies", "[]string"),
				fieldDecl("Tools", "[]string"),
				fieldDecl("Peers", "[]string"),
				fieldDecl("Targets", "[]string"),
				fieldDecl("RunTargets", "[]string"),
				fieldDecl("Projections", "[]string"),
				fieldDecl("HasPack", "bool"),
			}}},
		}},
	}
	variable := &ast.GenDecl{Tok: token.VAR, Specs: []ast.Spec{&ast.ValueSpec{Names: []*ast.Ident{layout.ident("generatedBuiltinCompositionCases")}, Type: sliceType("generatedCompositionCase", layout), Values: []ast.Expr{caseSlice(value.Cases, layout)}}}}
	names := make([]string, 0, len(value.Concepts))
	for _, concept := range value.Concepts {
		names = append(names, concept.Name)
	}
	namesVariable := &ast.GenDecl{Tok: token.VAR, Specs: []ast.Spec{&ast.ValueSpec{Names: []*ast.Ident{layout.ident("generatedBuiltinNames")}, Type: sliceType("string", layout), Values: []ast.Expr{stringSlice(names, layout)}}}}
	return formatFile(fset, value.Package, []ast.Decl{typeDecl, namesVariable, variable})
}

func formatFile(fset *token.FileSet, packageName string, declarations []ast.Decl) ([]byte, error) {
	file := &ast.File{Name: ast.NewIdent(packageName), Decls: declarations}
	var formatted bytes.Buffer
	if err := format.Node(&formatted, fset, file); err != nil {
		return nil, err
	}
	return append([]byte(generatedHeader), formatted.Bytes()...), nil
}

func fragmentSlice(values []concept, layout *sourceLayout) ast.Expr {
	elements := make([]ast.Expr, 0, len(values))
	for _, value := range values {
		layout.nextLine()
		elements = append(elements, fragmentLiteral(value, layout))
	}
	layout.nextLine()
	return &ast.CompositeLit{Type: sliceType("Fragment", layout), Lbrace: layout.take(), Elts: elements}
}

func fragmentLiteral(value concept, layout *sourceLayout) ast.Expr {
	manifest := []ast.Expr{}
	if value.WorkspaceName != "" {
		manifest = append(manifest, keyed("Workspace", pointerComposite("WorkspaceContribution", []ast.Expr{keyed("Name", stringLiteral(value.WorkspaceName, layout), layout)}, layout), layout))
	}
	if len(value.Dependencies) > 0 {
		manifest = append(manifest, keyed("Dependencies", dependencySlice(value.Dependencies, layout), layout))
	}
	if len(value.Tools) > 0 {
		manifest = append(manifest, keyed("Tools", dependencySlice(value.Tools, layout), layout))
	}
	if len(value.Peers) > 0 {
		manifest = append(manifest, keyed("Peers", dependencySlice(value.Peers, layout), layout))
	}
	if len(value.Targets) > 0 {
		manifest = append(manifest, keyed("Targets", targetSlice(value.Targets, layout), layout))
	}
	if len(value.RunTargets) > 0 {
		manifest = append(manifest, keyed("RunTargets", runTargetSlice(value.RunTargets, layout), layout))
	}
	if len(value.UpdatePolicy) > 0 {
		manifest = append(manifest, keyed("UpdatePolicy", policySlice(value.UpdatePolicy, layout), layout))
	}
	if len(value.SecurityPolicy) > 0 {
		manifest = append(manifest, keyed("SecurityPolicy", policySlice(value.SecurityPolicy, layout), layout))
	}
	if value.PackFormat != "" {
		manifest = append(manifest, keyed("Pack", pointerComposite("PackContribution", []ast.Expr{keyed("Format", stringLiteral(value.PackFormat, layout), layout), keyed("Artifact", stringLiteral(value.PackArtifact, layout), layout)}, layout), layout))
	}
	manifest = append(manifest, keyed("Concepts", stringSlice(value.ManifestConcepts, layout), layout))
	fields := []ast.Expr{keyed("Name", stringLiteral(value.Name, layout), layout)}
	if value.Description != "" {
		fields = append(fields, keyed("Description", stringLiteral(value.Description, layout), layout))
	}
	fields = append(fields, keyed("Provides", stringSlice(value.Provides, layout), layout))
	if len(value.Requires) > 0 {
		fields = append(fields, keyed("Requires", stringSlice(value.Requires, layout), layout))
	}
	if len(value.Conflicts) > 0 {
		fields = append(fields, keyed("Conflicts", stringSlice(value.Conflicts, layout), layout))
	}
	if len(value.CompatibleKinds) > 0 {
		fields = append(fields, keyed("CompatibleKinds", stringSlice(value.CompatibleKinds, layout), layout))
	}
	fields = append(fields, keyed("Manifest", composite("ManifestContributions", manifest, layout), layout))
	if len(value.Projections) > 0 {
		fields = append(fields, keyed("Projections", projectionContribution(value.Projections, layout), layout))
	}
	return composite("Fragment", fields, layout)
}

func caseSlice(values []compositionCase, layout *sourceLayout) ast.Expr {
	elements := make([]ast.Expr, 0, len(values))
	for _, value := range values {
		layout.nextLine()
		elements = append(elements, composite("generatedCompositionCase", []ast.Expr{
			keyed("Name", stringLiteral(value.Name, layout), layout), keyed("Kind", stringLiteral(value.Kind, layout), layout), keyed("Concepts", stringSlice(value.Concepts, layout), layout), keyed("Dependencies", stringSlice(value.Dependencies, layout), layout), keyed("Tools", stringSlice(value.Tools, layout), layout), keyed("Peers", stringSlice(value.Peers, layout), layout), keyed("Targets", stringSlice(value.Targets, layout), layout), keyed("RunTargets", stringSlice(value.RunTargets, layout), layout), keyed("Projections", stringSlice(value.Projections, layout), layout), keyed("HasPack", boolLiteral(value.HasPack, layout), layout),
		}, layout))
	}
	return &ast.CompositeLit{Type: sliceType("generatedCompositionCase", layout), Lbrace: layout.take(), Elts: elements}
}

