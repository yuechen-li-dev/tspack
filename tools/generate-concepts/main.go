// Command generate-concepts renders TSPack's Oct-derived built-in concept
// registry and its coordinated resolver-expectation table.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/ast"
	"go/format"
	"go/token"
	"os"

	experimental "github.com/yuechen-li-dev/oct/experimental/octgen"
)

const generatedHeader = "// Code generated by OctGen. DO NOT EDIT.\n// OctGen model: tspack-concepts.v1 (experimental).\n"

type dependency struct {
	Name   string
	Range  string
	Source string
}

type target struct {
	Name    string
	Export  string
	Entry   string
	Runtime string
	Types   string
}

type runTarget struct {
	Name    string
	Command string
}

type policy struct {
	Subject string
	Action  string
	Range   string
}

type projection struct {
	Object string
	Key    string
	Value  string
}

type concept struct {
	Name             string
	Description      string
	Provides         []string
	Requires         []string
	Conflicts        []string
	CompatibleKinds  []string
	Dependencies     []dependency
	Tools            []dependency
	Peers            []dependency
	Targets          []target
	RunTargets       []runTarget
	UpdatePolicy     []policy
	SecurityPolicy   []policy
	WorkspaceName    string
	PackFormat       string
	PackArtifact     string
	ManifestConcepts []string
	Projections      []projection
}

type compositionCase struct {
	Name         string
	Kind         string
	Concepts     []string
	Dependencies []string
	Tools        []string
	Peers        []string
	Targets      []string
	RunTargets   []string
	Projections  []string
	HasPack      bool
}

type model struct {
	Package  string
	Concepts []concept
	Cases    []compositionCase
}

func main() {
	if len(os.Args) < 2 {
		fatal("usage: generate-concepts <generate|check> -input concepts.oct -output builtin_registry.generated.go -test-output builtin_registry.generated_test.go")
	}
	command := os.Args[1]
	flags := flag.NewFlagSet("generate-concepts "+command, flag.ExitOnError)
	input := flags.String("input", "", "Oct concept generator")
	output := flags.String("output", "", "generated registry Go")
	testOutput := flags.String("test-output", "", "generated resolver expectations Go")
	flags.Parse(os.Args[2:])
	if *input == "" || *output == "" || *testOutput == "" {
		fatal("-input, -output, and -test-output are required")
	}

	value, err := experimental.Execute(*input)
	if err != nil {
		fatal("execute: %v", err)
	}
	decoded, err := decodeModel(value, *input)
	if err != nil {
		fatal("decode: %v", err)
	}
	registry, err := renderRegistry(decoded)
	if err != nil {
		fatal("render registry: %v", err)
	}
	expectations, err := renderExpectations(decoded)
	if err != nil {
		fatal("render expectations: %v", err)
	}
	artifacts := []experimental.Artifact{{Path: *output, Content: registry}, {Path: *testOutput, Content: expectations}}
	switch command {
	case "generate":
		err = experimental.Write(*input, artifacts)
	case "check":
		err = experimental.Check(*input, artifacts)
	default:
		fatal("unknown command %q; expected generate or check", command)
	}
	if err != nil {
		fatal("%s: %v", command, err)
	}
}

func decodeModel(value experimental.Value, provenance string) (model, error) {
	if value.Kind != experimental.ValueRecord || value.Record.TypeName != "GeneratedTSPackConceptRegistry" {
		return model{}, modelError(provenance, "Generate must return GeneratedTSPackConceptRegistry")
	}
	packageName, err := requiredString(value.Record.Fields, "Package", provenance)
	if err != nil {
		return model{}, err
	}
	if packageName != "concepts" {
		return model{}, modelError(provenance, "Package must be concepts, got %q", packageName)
	}
	conceptValues, err := requiredArray(value.Record.Fields, "Concepts", provenance)
	if err != nil {
		return model{}, err
	}
	if len(conceptValues) < 10 {
		return model{}, modelError(provenance, "Concepts must contain at least ten concepts")
	}
	decoded := model{Package: packageName, Concepts: make([]concept, 0, len(conceptValues))}
	seen := map[string]struct{}{}
	for index, item := range conceptValues {
		entry, err := decodeConcept(item, provenance, index)
		if err != nil {
			return model{}, err
		}
		if _, exists := seen[entry.Name]; exists {
			return model{}, modelError(provenance, "Concepts[%d].Name %q is duplicated", index, entry.Name)
		}
		seen[entry.Name] = struct{}{}
		decoded.Concepts = append(decoded.Concepts, entry)
	}
	caseValues, err := requiredArray(value.Record.Fields, "Cases", provenance)
	if err != nil {
		return model{}, err
	}
	if len(caseValues) < 3 {
		return model{}, modelError(provenance, "Cases must contain at least three coordinated resolver cases")
	}
	decoded.Cases = make([]compositionCase, 0, len(caseValues))
	for index, item := range caseValues {
		entry, err := decodeCase(item, provenance, index, seen)
		if err != nil {
			return model{}, err
		}
		decoded.Cases = append(decoded.Cases, entry)
	}
	return decoded, nil
}

func decodeConcept(value experimental.Value, provenance string, index int) (concept, error) {
	if value.Kind != experimental.ValueRecord || value.Record.TypeName != "Concept" {
		return concept{}, modelError(provenance, "Concepts[%d] must be Concept", index)
	}
	fields := value.Record.Fields
	entry := concept{}
	var err error
	for _, target := range []struct {
		name string
		out  *string
	}{{"Name", &entry.Name}, {"Description", &entry.Description}, {"WorkspaceName", &entry.WorkspaceName}, {"PackFormat", &entry.PackFormat}, {"PackArtifact", &entry.PackArtifact}} {
		*target.out, err = requiredString(fields, target.name, provenance)
		if err != nil {
			return concept{}, err
		}
	}
	if entry.Name == "" {
		return concept{}, modelError(provenance, "Concepts[%d].Name must not be empty", index)
	}
	entry.Provides, err = stringList(fields, "Provides", provenance)
	if err != nil {
		return concept{}, err
	}
	if len(entry.Provides) != 1 || entry.Provides[0] != entry.Name {
		return concept{}, modelError(provenance, "Concepts[%d].Provides must derive the concept name", index)
	}
	for _, target := range []struct {
		name string
		out  *[]string
	}{{"Requires", &entry.Requires}, {"Conflicts", &entry.Conflicts}, {"CompatibleKinds", &entry.CompatibleKinds}, {"ManifestConcepts", &entry.ManifestConcepts}} {
		*target.out, err = stringList(fields, target.name, provenance)
		if err != nil {
			return concept{}, err
		}
	}
	if len(entry.ManifestConcepts) != 1 || entry.ManifestConcepts[0] != entry.Name {
		return concept{}, modelError(provenance, "Concepts[%d].ManifestConcepts must derive the concept name", index)
	}
	if entry.Dependencies, err = dependencyList(fields, "Dependencies", provenance); err != nil {
		return concept{}, err
	}
	if entry.Tools, err = dependencyList(fields, "Tools", provenance); err != nil {
		return concept{}, err
	}
	if entry.Peers, err = dependencyList(fields, "Peers", provenance); err != nil {
		return concept{}, err
	}
	if entry.Targets, err = targetList(fields, "Targets", provenance); err != nil {
		return concept{}, err
	}
	if entry.RunTargets, err = runTargetList(fields, "RunTargets", provenance); err != nil {
		return concept{}, err
	}
	if entry.UpdatePolicy, err = policyList(fields, "UpdatePolicy", provenance); err != nil {
		return concept{}, err
	}
	if entry.SecurityPolicy, err = policyList(fields, "SecurityPolicy", provenance); err != nil {
		return concept{}, err
	}
	if entry.Projections, err = projectionList(fields, "Projections", provenance); err != nil {
		return concept{}, err
	}
	return entry, nil
}

func decodeCase(value experimental.Value, provenance string, index int, concepts map[string]struct{}) (compositionCase, error) {
	if value.Kind != experimental.ValueRecord || value.Record.TypeName != "CompositionCase" {
		return compositionCase{}, modelError(provenance, "Cases[%d] must be CompositionCase", index)
	}
	fields := value.Record.Fields
	entry := compositionCase{}
	var err error
	entry.Name, err = requiredString(fields, "Name", provenance)
	if err != nil {
		return compositionCase{}, err
	}
	entry.Kind, err = requiredString(fields, "Kind", provenance)
	if err != nil {
		return compositionCase{}, err
	}
	for _, target := range []struct {
		name string
		out  *[]string
	}{{"Concepts", &entry.Concepts}, {"Dependencies", &entry.Dependencies}, {"Tools", &entry.Tools}, {"Peers", &entry.Peers}, {"Targets", &entry.Targets}, {"RunTargets", &entry.RunTargets}, {"Projections", &entry.Projections}} {
		*target.out, err = stringList(fields, target.name, provenance)
		if err != nil {
			return compositionCase{}, err
		}
	}
	for _, name := range entry.Concepts {
		if _, ok := concepts[name]; !ok {
			return compositionCase{}, modelError(provenance, "Cases[%d] references unknown concept %q", index, name)
		}
	}
	packed, ok := fields["HasPack"]
	if !ok || packed.Kind != experimental.ValueBool {
		return compositionCase{}, modelError(provenance, "Cases[%d].HasPack must be Bool", index)
	}
	entry.HasPack = packed.Bool
	return entry, nil
}

func requiredString(fields map[string]experimental.Value, name, provenance string) (string, error) {
	value, ok := fields[name]
	if !ok || value.Kind != experimental.ValueString {
		return "", modelError(provenance, "%s must be String", name)
	}
	return value.Text, nil
}

func requiredArray(fields map[string]experimental.Value, name, provenance string) ([]experimental.Value, error) {
	value, ok := fields[name]
	if !ok || value.Kind != experimental.ValueArray {
		return nil, modelError(provenance, "%s must be an array", name)
	}
	return value.Array, nil
}

func stringList(fields map[string]experimental.Value, name, provenance string) ([]string, error) {
	values, err := requiredArray(fields, name, provenance)
	if err != nil {
		return nil, err
	}
	result := make([]string, 0, len(values))
	seen := map[string]struct{}{}
	for index, value := range values {
		if value.Kind != experimental.ValueString || value.Text == "" {
			return nil, modelError(provenance, "%s[%d] must be a non-empty String", name, index)
		}
		if _, exists := seen[value.Text]; exists {
			return nil, modelError(provenance, "%s[%d] duplicates %q", name, index, value.Text)
		}
		seen[value.Text] = struct{}{}
		result = append(result, value.Text)
	}
	return result, nil
}

func dependencyList(fields map[string]experimental.Value, name, provenance string) ([]dependency, error) {
	values, err := requiredArray(fields, name, provenance)
	if err != nil {
		return nil, err
	}
	result := make([]dependency, 0, len(values))
	for index, value := range values {
		if value.Kind != experimental.ValueRecord || value.Record.TypeName != "Dependency" {
			return nil, modelError(provenance, "%s[%d] must be Dependency", name, index)
		}
		entry := dependency{}
		entry.Name, err = requiredString(value.Record.Fields, "Name", provenance)
		if err != nil {
			return nil, err
		}
		entry.Range, err = requiredString(value.Record.Fields, "Range", provenance)
		if err != nil {
			return nil, err
		}
		entry.Source, err = requiredString(value.Record.Fields, "Source", provenance)
		if err != nil {
			return nil, err
		}
		if entry.Name == "" || entry.Source != "npm" {
			return nil, modelError(provenance, "%s[%d] must have a name and derived npm source", name, index)
		}
		result = append(result, entry)
	}
	return result, nil
}

func targetList(fields map[string]experimental.Value, name, provenance string) ([]target, error) {
	values, err := requiredArray(fields, name, provenance)
	if err != nil {
		return nil, err
	}
	result := make([]target, 0, len(values))
	for index, value := range values {
		if value.Kind != experimental.ValueRecord || value.Record.TypeName != "Target" {
			return nil, modelError(provenance, "%s[%d] must be Target", name, index)
		}
		entry := target{}
		for _, field := range []struct {
			name string
			out  *string
		}{{"Name", &entry.Name}, {"Export", &entry.Export}, {"Entry", &entry.Entry}, {"Runtime", &entry.Runtime}, {"Types", &entry.Types}} {
			entryValue, fieldErr := requiredString(value.Record.Fields, field.name, provenance)
			if fieldErr != nil {
				return nil, fieldErr
			}
			*field.out = entryValue
		}
		result = append(result, entry)
	}
	return result, nil
}

